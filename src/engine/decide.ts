/** DS-v0.1 — initial action catalog proposed for review (spec §9.5). */
export const CATALOG: Record<Action, { en: string; ar: string; describe: (a: string, ar: string) => { en: string; ar: string } }> = {
  monitor: { en: "Monitor", ar: "مراقبة", describe: (a, ar) => ({ en: `Continue monitoring ${a}.`, ar: `استمرار مراقبة ${ar}.` }) },
  verify: { en: "Verify", ar: "تحقق", describe: (a, ar) => ({ en: `Verify sensor readings and field conditions for ${a}.`, ar: `التحقق من قراءات الحساسات والحالة الميدانية في ${ar}.` }) },
  notify: { en: "Notify", ar: "إبلاغ", describe: (a, ar) => ({ en: `Notify the authorized monitoring team about ${a}.`, ar: `إبلاغ فريق المراقبة المخوّل بشأن ${ar}.` }) },
  escalate: { en: "Escalate", ar: "تصعيد", describe: (a, ar) => ({ en: `Escalate ${a} to the authorized operator for a human decision.`, ar: `رفع حالة ${ar} إلى المشغّل المخوّل لاتخاذ القرار.` }) },
  prepare: { en: "Prepare", ar: "استعداد", describe: (a, ar) => ({ en: `Prepare predefined procedures for ${a} for review, if any exist.`, ar: `تجهيز الإجراءات المعتمدة مسبقًا لـ ${ar} للمراجعة، إن وُجدت.` }) },
};


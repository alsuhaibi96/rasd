export const ACTION_ORDER: Action[] = ["escalate", "prepare", "notify", "verify", "monitor"];

/** Documented mapping area state → actions. */
export function actionsFor(r: AreaResult): Action[] {
  switch (r.risk) {
    case "severe":
      return ["escalate", "prepare"];
    case "elevated":
      return ["notify"];
    case "moderate":
      return r.receding ? ["monitor"] : ["verify"];
    case "low":
      return ["monitor"];
    case "no_data":
      return ["verify"];
    default:
      return [];
  }
}

export function recommendationText(action: Action, a: AreaDef) {
  return CATALOG[action].describe(a.name.en, a.name.ar);
}

export function reasonFor(action: Action, r: AreaResult, rank: RankRow | undefined) {
  const R = RISK_LABEL[r.risk];
  const rk = rank ? `#${rank.rank}${rank.tie ? " (tie)" : ""}` : "—";
  const rkAr = rank ? `#${rank.rank}${rank.tie ? " (تعادل)" : ""}` : "—";
  const why: Record<Action, { en: string; ar: string }> = {
    escalate: { en: "Severe conditions need a human decision", ar: "الظروف الشديدة تتطلب قرارًا بشريًا" },
    prepare: { en: "Severe conditions: have predefined procedures ready for review", ar: "ظروف شديدة: تجهيز الإجراءات المعتمدة للمراجعة" },
    notify: { en: "Two or more consistent indicators deviating", ar: "مؤشران متسقان أو أكثر منحرفة" },
    verify: r.risk === "no_data" ? { en: "No assessable data for this area", ar: "لا توجد بيانات قابلة للتقييم لهذه المنطقة" } : { en: "One indicator deviating", ar: "مؤشر واحد منحرف" },
    monitor: r.receding ? { en: "Level receding but still above baseline", ar: "المستوى يتراجع لكنه أعلى من الوضع الاعتيادي" } : { en: "No deviating indicators", ar: "لا توجد مؤشرات منحرفة" },
  };
  return { en: `${why[action].en}. Area risk ${R.en}, priority ${rk}.`, ar: `${why[action].ar}. خطر المنطقة ${R.ar}، الأولوية ${rkAr}.` };
}

export function hasForbidden(text: string) {
  return FORBIDDEN.some((re) => re.test(text));
}
